    private const string SamplePngDataUri =
        "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==";

    [Fact]
    public void ShopBranding_SanitizesLogoAndUrls_RejectingUnsafeSchemesAndSvg()
    {
        Assert.Equal(SamplePngDataUri, ShopBranding.SanitizeLogoDataUri("  " + SamplePngDataUri + " \n"));
        Assert.Equal("data:image/webp;base64,UklGRh4AAABXRUJQVlA4TBEAAAAvAAAAAAfQ//73v/+BiOh/AAA=",
            ShopBranding.SanitizeLogoDataUri("data:image/webp;base64,UklGRh4AAABXRUJQVlA4TBEAAAAvAAAAAAfQ//73v/+BiOh/AAA="));

        // Reject SVG (XSS vector), remote tracking beacons, script URIs, and oversized payloads.
        Assert.Null(ShopBranding.SanitizeLogoDataUri("data:image/svg+xml;base64,PHN2Zz48L3N2Zz4="));
        Assert.Null(ShopBranding.SanitizeLogoDataUri("https://evil.example/pixel.png"));
        Assert.Null(ShopBranding.SanitizeLogoDataUri("javascript:alert(1)"));
        Assert.Null(ShopBranding.SanitizeLogoDataUri("data:image/png;base64," + new string('A', ShopBranding.MaxLogoDataUriLength)));

        Assert.Equal("https://acmerepair.example/", ShopBranding.SanitizeHttpUrl("acmerepair.example"));
        Assert.Equal("https://reports.acmerepair.example/r", ShopBranding.SanitizeHttpUrl("https://reports.acmerepair.example/r"));
        Assert.Null(ShopBranding.SanitizeHttpUrl("javascript:alert(1)"));
        Assert.Null(ShopBranding.SanitizeHttpUrl("data:text/html,hi"));
    }

