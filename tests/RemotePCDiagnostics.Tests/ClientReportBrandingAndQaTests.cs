    [Fact]
    public void QrCodeSvg_MatchesIso18004VectorsAndScalesAcrossVersions()
    {
        // ISO/IEC 18004 Annex C / D BCH format & version info test vectors
        Assert.Equal(0x5412, QrCodeSvg.ComputeFormatBits(0, 0));
        Assert.Equal(0x5E7C, QrCodeSvg.ComputeFormatBits(0, 2));
        Assert.Equal(0x07C94, QrCodeSvg.ComputeVersionBits(7));

        // Version 1 (21x21): short payload
        var v1 = QrCodeSvg.EncodeMatrix("QA-123");
        Assert.Equal(21, v1.GetLength(0));
        Assert.Equal(21, v1.GetLength(1));
        Assert.True(v1[0, 0]);           // Top-left finder corner
        Assert.True(v1[3, 3]);           // Top-left finder center
        Assert.False(v1[1, 1]);          // Top-left finder inner ring
        Assert.True(v1[21 - 8, 8]);      // Always-dark module (4*V + 9, 8)

        // Version 7+ (45x45+): longer URL payload triggers multi-block RS + version info bits
        var longUrl = "https://reports.remoteblazorwebview.com/r/QA-20261112-A1B2C3?sn=5CG1234XYZ&model=Dell+Latitude+7420+Refurbished+Grade+A&hash=9f86d081884c7d659a2feaa0";
        var vLarge = QrCodeSvg.EncodeMatrix(longUrl);
        Assert.True(vLarge.GetLength(0) >= 45);
        Assert.True(vLarge[vLarge.GetLength(0) - 8, 8]);

        var svg = QrCodeSvg.Render("RPD-QA|QA-20261112-ABCDEF|PASS", quietZoneModules: 2);
        Assert.StartsWith("<svg ", svg);
        Assert.EndsWith("</svg>", svg);
        Assert.Contains("<path fill=\"#111827\" d=\"M", svg);
    }

    [Fact]
    public void HardwareQaCertificate_BuildsCertifiedPassWithHardwareSpecsDongleFreeAudioAndQr()
    {
        var store = new ResultStore();
        var sys = new SystemInfo(
            Hostname: "refurb-bench-04", ComputerName: "REFURB-04", Uuid: "1111-2222",
            HardwareVendor: "Dell Inc.", HardwareModel: "Latitude 7420", HardwareVersion: "A01", HardwareSerial: "8H9K2L3",
            BoardVendor: "Dell Inc.", BoardModel: "0PKK8F", BoardVersion: "A00", BoardSerial: "CN0PKK8F",
            CpuBrand: "11th Gen Intel(R) Core(TM) i7-1185G7", CpuType: "x86_64", CpuPhysicalCores: 4, CpuLogicalCores: 8, CpuSockets: 1,
            PhysicalMemoryBytes: 16L * 1024 * 1024 * 1024);
        var inv = new HardwareInventory(
            new InventorySection<SystemInfo>(HardwareInventory.SystemSql, [sys], null),
            new InventorySection<CpuInfo>(HardwareInventory.CpuSql, [HardwareInventory.CpuFromSystemPublic(sys)], null),
            new InventorySection<MemoryDevice>(HardwareInventory.MemorySql, [
                new MemoryDevice("DIMM A", "BANK 0", "SODIMM", "LPDDR4", 8192, 4267, 4267, "Micron", "MT53E", "001"),
                new MemoryDevice("DIMM B", "BANK 1", "SODIMM", "LPDDR4", 8192, 4267, 4267, "Micron", "MT53E", "002")
            ], null),
            new InventorySection<DiskInfo>(HardwareInventory.DiskSql, [
                new DiskInfo(0, "Disk0", "NVMe0", "NVMe", "Samsung", "PM991a NVMe 512GB", "S660NX0", "SSD", 512L * 1024 * 1024 * 1024, 3)
            ], null));

        var now = new DateTimeOffset(2026, 11, 12, 14, 0, 0, TimeSpan.Zero);
        store.Set(new DiagnosticResult(ModuleSlugs.Osquery, DiagnosticStatus.Ok, "Hardware collected", now, inv));
        store.Set(new DiagnosticResult(ModuleSlugs.BatteryPower, DiagnosticStatus.Ok, "92% design capacity", now,
            new AreaReport([], "Battery at 92% of original design capacity", DiagnosticStatus.Ok)));
        store.Set(new DiagnosticResult(ModuleSlugs.DriveHealth, DiagnosticStatus.Ok, "Healthy", now,
            new AreaReport([], "Healthy · 2% wear · 34 °C", DiagnosticStatus.Ok)));
        store.Set(new DiagnosticResult(ModuleSlugs.Sensors, DiagnosticStatus.Ok, "Temperatures normal", now));
        store.Set(new DiagnosticResult(ModuleSlugs.CpuStress, DiagnosticStatus.Ok, "Passed (short run)", now));
        store.Set(new DiagnosticResult(ModuleSlugs.MemoryTest, DiagnosticStatus.Ok, "0 errors (Quick)", now));
        store.Set(new DiagnosticResult(ModuleSlugs.DiskSpeed, DiagnosticStatus.Ok, "Passed", now,
            new DiskSpeedReport(DiskSpeedOutcome.Passed, "C:\\", 1024 * 1024 * 256, TimeSpan.FromSeconds(30), 1850, 3120, 42000, 68000, 256, 0, 44, true)));
        store.Set(new DiagnosticResult(ModuleSlugs.SpeakerToMic, DiagnosticStatus.Ok, "Tone detected (+24 dB SNR)", now));
        store.Set(new DiagnosticResult(ModuleSlugs.MicToSpeaker, DiagnosticStatus.Ok, "Confirmed audible", now));
        store.Set(new DiagnosticResult(ModuleSlugs.Webcam, DiagnosticStatus.Ok, "30 fps, normal exposure", now));

        var branding = new ShopBranding
        {
            ShopName = "Metro Refurbished Laptops",
            LogoDataUri = SamplePngDataUri,
            WarrantyFooter = "1-Year Refurbisher Hardware Guarantee",
            VerificationBaseUrl = "https://reports.metrorefurb.example/cert",
        };

        var snap = HardwareQaCertificate.Capture(store, "REFURB-04", now, branding, operatingSystem: "Windows 11 Pro 24H2");
        Assert.Equal(HardwareQaVerdict.CertifiedPass, snap.Verdict);
        Assert.Equal("Dell Inc. Latitude 7420", snap.ManufacturerModel);
        Assert.Equal("8H9K2L3", snap.SerialNumber);
        Assert.Contains("2 DIMMs", snap.Memory);
        Assert.Contains("4267 MT/s", snap.Memory);
        Assert.Contains("PM991a NVMe 512GB", snap.Storage);
        Assert.StartsWith("https://reports.metrorefurb.example/cert/QA-20261112-", snap.QrPayload);

        var html = HardwareQaCertificate.BuildHtml(snap);
        Assert.Contains("CERTIFIED HARDWARE PASS", html);
        Assert.Contains("Metro Refurbished Laptops — Hardware QA Certificate", html);
        Assert.Contains("8H9K2L3", html);
        Assert.Contains("Seq read 3120 MB/s · Seq write 1850 MB/s", html);
        Assert.Contains("Speaker→Mic: Tone detected (+24 dB SNR) · Mic→Speaker: Confirmed audible", html);
        Assert.Contains("<svg ", html);
        Assert.Contains("1-Year Refurbisher Hardware Guarantee", html);

        // UserPreferences round-trip serialization preserves ShopBranding.
        var prefsStore = new MemoryPreferencesStore();
        var prefs = new PreferencesService(prefsStore);
        prefs.Update(p => p with { Branding = branding.Normalized() });
        Assert.Equal("Metro Refurbished Laptops", prefs.Current.Branding?.ShopName);
    }
